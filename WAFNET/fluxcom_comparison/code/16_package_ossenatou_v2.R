## ---- xbase_005_monthly.csv (centre cell, row_offset=col_offset=0) and
## xbase_005_neighbours_monthly.csv (full 3x3 block), both wide by variable with a source_key
## column per variable, both built from the same re-verified raw extraction table. --------------
raw_wide <- raw |>
  tidyr::pivot_wider(
    id_cols = c(site_id, row_offset, col_offset, year, month, tower_lon, tower_lat, cell_lon, cell_lat, cell_dist_km),
    names_from = variable, values_from = c(value, source_key)
  ) |>
  dplyr::rename(
    GPP_gC_m2_d1 = value_GPP, NEE_gC_m2_d1 = value_NEE,
    ET_mm_hr = value_ET, ET_T_mm_hr = value_ET_T,
    source_key_GPP = source_key_GPP, source_key_NEE = source_key_NEE,
    source_key_ET = source_key_ET, source_key_ET_T = source_key_ET_T
  ) |>
  dplyr::mutate(LE_W_m2 = ET_mm_hr * LAMBDA_J_PER_KG / 3600)

cell_info <- raw_wide |>
  dplyr::distinct(site_id, row_offset, col_offset, tower_lon, tower_lat, cell_lon, cell_lat, cell_dist_km)

all_grid_nb <- tidyr::expand_grid(
  cell_info |> dplyr::select(site_id, row_offset, col_offset),
  year = XBASE005_YEARS, month = 1:12
)
xbase_005_neighbours_monthly <- all_grid_nb |>
  dplyr::left_join(
    raw_wide |> dplyr::select(site_id, row_offset, col_offset, year, month,
                               GPP_gC_m2_d1, NEE_gC_m2_d1, ET_mm_hr, ET_T_mm_hr, LE_W_m2,
                               source_key_GPP, source_key_NEE, source_key_ET, source_key_ET_T),
    by = c("site_id", "row_offset", "col_offset", "year", "month")
  ) |>
  dplyr::left_join(cell_info, by = c("site_id", "row_offset", "col_offset")) |>
  dplyr::arrange(site_id, row_offset, col_offset, year, month) |>
  dplyr::select(site_id, row_offset, col_offset, year, month,
                GPP_gC_m2_d1, NEE_gC_m2_d1, ET_mm_hr, ET_T_mm_hr, LE_W_m2,
                cell_lon, cell_lat, cell_dist_km, tower_lon, tower_lat,
                source_key_GPP, source_key_NEE, source_key_ET, source_key_ET_T)

xbase_005_monthly <- xbase_005_neighbours_monthly |>
  dplyr::filter(row_offset == 0, col_offset == 0) |>
  dplyr::select(-row_offset, -col_offset)

utils::write.csv(xbase_005_monthly, file.path(PKG_DIR, "xbase_005_monthly.csv"), row.names = FALSE)
utils::write.csv(xbase_005_neighbours_monthly, file.path(PKG_DIR, "xbase_005_neighbours_monthly.csv"), row.names = FALSE)

