## generate_site_reference_list.R
##
## Generates the full site reference list for the FLUXNET Annual Paper:
## one BibTeX entry per site, an APA 7th Edition reference list (.txt and
## .docx), an acknowledgments.md following the FLUXNET data use policy
## (https://data.fluxnet.org/?p=30), and a review-flags.md -- all written to
## review/citations/ (git-tracked, alongside review/figures/), with a
## companion .meta.json for provenance per CLAUDE.md.
##
## Follows the decisions recorded in SESSION_LOG.md's 2026-10-13 citation-
## generator audit (commit bbbd02c) and this run's own follow-up entry:
##   1. parse_saeon() fixed to handle no-author citations (mirrors
##      parse_icos()'s existing no-author branch) -- all 781 sites now parse.
##   2. Snapshot pinned explicitly below, not auto-discovered. Does not
##      regenerate any figures.
##   3. Network references (JPF/CNF/TERN) and the acknowledgments text
##      corrected against the FLUXNET data use policy -- see
##      scripts/generate_fluxnet_citations.R's mandated_bib() and
##      build_acknowledgments() for the specifics.
##   4. Outputs committed under review/citations/, never to
##      bib_to_apa()'s default Google Drive path.
##
## Run from the repository root: Rscript scripts/generate_site_reference_list.R

if (file.exists(".env")) {
  library(dotenv)
  dotenv::load_dot_env()
}
source("R/pipeline_config.R")
source("R/utils.R")
check_pipeline_config()

source("scripts/generate_fluxnet_citations.R")
source("R/parse_bib_to_apa.R")

suppressPackageStartupMessages({
  library(dplyr)
  library(readr)
})

msg <- function(...) message(format(Sys.time(), "[%Y-%m-%d %H:%M:%S]"), " ", ...)
msg("=== Generating the full site reference list for the paper ===")

## ---- Decision 2: explicit snapshot pin, no auto-discovery -------------------
SNAPSHOT_PATH <- "data/snapshots/fluxnet_shuttle_snapshot_20260920T102211.csv"
if (!file.exists(SNAPSHOT_PATH)) stop("Pinned snapshot not found: ", SNAPSHOT_PATH)

OUT_DIR    <- "review/citations"
OUT_PREFIX <- file.path(OUT_DIR, "fluxnet_site_references")
fs::dir_create(OUT_DIR)

sites <- read_csv(SNAPSHOT_PATH, show_col_types = FALSE) |>
  distinct(site_id, .keep_all = TRUE)
msg("Snapshot: ", basename(SNAPSHOT_PATH), " -- ", nrow(sites), " distinct sites")

## ---- Stage 1: BibTeX + acknowledgments + review flags -----------------------
res <- generate_fluxnet_citations(
  site_ids      = sites$site_id,
  snapshot_path = SNAPSHOT_PATH,
  output_prefix = OUT_PREFIX
)

bib_lines      <- readLines(res$bib)
n_misc_entries <- sum(grepl("^@misc", bib_lines))
msg("Stage 1 (BibTeX): ", n_misc_entries, " of ", nrow(sites), " sites parsed; ",
    res$n_flags, " review flag(s); networks: ", paste(res$networks, collapse = ", "))

## ---- Stage 2: APA reference list (.txt and .docx) ---------------------------
## Explicit out_path for both -- never bib_to_apa()'s default Google Drive
## sync path (CLAUDE.md: never write outside the repository directory without
## asking first; the GDrive default is exactly that).
apa_txt  <- bib_to_apa(bib_path = res$bib, out_path = paste0(OUT_PREFIX, "_apa.txt"),
                       output_format = "txt")
apa_docx <- bib_to_apa(bib_path = res$bib, out_path = paste0(OUT_PREFIX, "_apa.docx"),
                       output_format = "docx")
msg("Stage 2 (APA): ", apa_txt$n, " citations -> ", apa_txt$out_path, " and ", apa_docx$out_path)

## ---- Per-network reference counts (from the snapshot, not the .bib, so the
## count includes sites whose entry failed to parse too) -----------------------
net_counts <- sites |>
  filter(site_id %in% sites$site_id) |>
  count(product_source_network, sort = TRUE)
msg("Sites by network:")
for (i in seq_len(nrow(net_counts))) {
  msg("  ", net_counts$product_source_network[i], ": ", net_counts$n[i])
}

## ---- Provenance metadata -----------------------------------------------------
write_output_metadata(
  res$bib,
  input_sources = c(SNAPSHOT_PATH),
  notes = paste0(
    "Generated by scripts/generate_site_reference_list.R. ", n_misc_entries, " of ",
    nrow(sites), " sites parsed into BibTeX; ", res$n_flags, " review flag(s) remain ",
    "(see fluxnet_site_references_review_flags.md). Network references (JPF/CNF/TERN) ",
    "and acknowledgments text corrected 2026-10-14 against the FLUXNET data use policy ",
    "(https://data.fluxnet.org/?p=30) -- see SESSION_LOG.md. APA list in ",
    basename(apa_txt$out_path), " and ", basename(apa_docx$out_path), "."
  )
)
msg("Wrote: ", paste0(OUT_PREFIX, ".meta.json"))

msg("=== Done ===")
msg("Outputs in ", OUT_DIR, "/:")
msg("  ", res$bib)
msg("  ", res$ack)
msg("  ", res$flags)
msg("  ", apa_txt$out_path)
msg("  ", apa_docx$out_path)
msg("  ", paste0(OUT_PREFIX, ".meta.json"))
